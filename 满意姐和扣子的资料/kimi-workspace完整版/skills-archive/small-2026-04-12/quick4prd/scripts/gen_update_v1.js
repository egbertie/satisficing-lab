// 从 .md 源文件中读取「文档版本」字段，如 | 文档版本 | v0.4 |
function readVersionFromMd(mdPath) {
  if (!fs.existsSync(mdPath)) return null;
  const content = fs.readFileSync(mdPath, 'utf8');
  const m = content.match(/\|\s*文档版本\s*\|\s*(v[\d.]+)\s*\|/);
  return m ? m[1] : null;
}

async function generateDoc(outDir, entry) {
  const backupDir = path.join(outDir, 'backup');
  if (!fs.existsSync(backupDir)) fs.mkdirSync(backupDir, { recursive: true });

  // 归档旧版本快照（生成新版本前，将旧版本移入 backup）
  const files = fs.readdirSync(outDir);
  const re = new RegExp(`^${entry.base.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}_v(\\d+)\\.(\\d+)\\.(docx|md)$`);
  files.forEach(f => {
    if (re.test(f)) {
      fs.renameSync(path.join(outDir, f), path.join(backupDir, f));
      console.log(`  → 已归档旧版本：${f}`);
    }
  });

  // 优先读取源文件 md 中的「文档版本」字段作为快照版本号
  const mdSrcPath = path.join(outDir, `${entry.base}.md`);
  const verFromMd = readVersionFromMd(mdSrcPath);
  const ver = verFromMd || nextVersion(outDir, entry.base);
  if (verFromMd) {
    console.log(`  → 版本号取自源文件：${ver}`);
  }
  const docxName = `${entry.base}_${ver}.docx`;
  const mdName   = `${entry.base}_${ver}.md`;

  // 生成 docx（仅当有 build 函数时）
  if (entry.build) {
    const buf = await docx.Packer.toBuffer(entry.build());
    fs.writeFileSync(path.join(outDir, docxName), buf);
    console.log(`✓ ${docxName}`);
  } else {
    console.log(`⚠ ${entry.base}：无 build 函数，跳过 docx 生成`);
  }

  // 同步复制最新 .md 源文件并加版本后缀
  const mdSrc = path.join(outDir, `${entry.base}.md`);
  if (fs.existsSync(mdSrc)) {
    fs.copyFileSync(mdSrc, path.join(outDir, mdName));
    console.log(`✓ ${mdName}`);
  } else {
    console.log(`⚠ 未找到 md 源文件：${entry.base}.md，跳过 md 快照`);
  }
}

async function main() {
  const outDir = process.env.DOC_DIR || require('path').join(process.cwd(), 'tongyiyunying', 'doc');

  // 解析命令行参数 --doc <key1,key2,...> 或 --doc <key1> --doc <key2>
  const args = process.argv.slice(2);
  const requestedKeys = [];
  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--doc' && args[i + 1]) {
      args[i + 1].split(',').forEach(k => requestedKeys.push(k.trim()));
      i++;
    }
  }

  // 确定要生成的文档列表
  let targets = [];
  if (requestedKeys.length > 0) {
    for (const key of requestedKeys) {
      if (ALL_DOCS[key]) {
        targets.push(ALL_DOCS[key]);
      } else {
        console.error(`✗ 未知文档 key: "${key}"，可用 key：${Object.keys(ALL_DOCS).join('、')}`);
        process.exit(1);
      }
    }
  } else {
    // 不传参数 = 生成全部（兼容旧行为）
    targets = Object.values(ALL_DOCS);
  }

  console.log(`\n📄 本次将生成 ${targets.length} 个文档快照：`);
  targets.forEach(t => console.log(`   - ${t.base}`));
  console.log('');

  for (const entry of targets) {
    await generateDoc(outDir, entry);
  }

  console.log('\n✅ 完成');
}

main().catch(console.error);
