def query_concept(keyword: str) -> List[Tuple[str, str, str]]:
    """按關鍵詞跨庫檢索儒商概念，返回 (來源, 主題, 內容摘要) 列表。"""
    results = []
    keyword = keyword.strip()
    # 搜索十大觀念
    for view_name, content in KNOWLEDGE_BASE["ten_views"]["views"].items():
        text_blob = str(content)
        if keyword in text_blob or keyword in view_name:
            results.append(("十大觀念", view_name, content.get("classic", "")))
    # 搜索八大道
    for way_name, content in KNOWLEDGE_BASE["eight_ways"]["ways"].items():
        text_blob = str(content)
        if keyword in text_blob or keyword in way_name:
            results.append(("八大道", f"{way_name}：{content['subtitle']}", content.get("case", "")))
    # 搜索十論
    for theory_name, content in KNOWLEDGE_BASE["ten_theories"]["theories"].items():
        text_blob = str(content)
        if keyword in text_blob or keyword in theory_name:
            results.append(("十論", theory_name, content.get("summary", "")))
    return results


class ConfucianBusinessAssessor:
    """
    儒商價值觀五維評估器（基於仁義禮智信五常）。
    簡化版：輸入五維自評分數（1-10），輸出綜合評價與改進建議。
    """

    DIMENSIONS = {
        "仁": "愛人、推己及人、關懷員工與客戶",
        "義": "見利思義、義利合一、經營有道",
        "禮": "齊之以禮、規矩方圆、文化規範",
        "智": "格物致知、知治一致、戰略遠見",
        "信": "內誠於心、外信於人、品牌誠信"
    }

    def __init__(self):
        self.scores: Dict[str, int] = {}

    def input_scores(self, ren: int, yi: int, li: int, zhi: int, xin: int):
        for k, v in [("仁", ren), ("義", yi), ("禮", li), ("智", zhi), ("信", xin)]:
            self.scores[k] = max(1, min(10, v))

    def evaluate(self) -> Dict:
        if not self.scores:
            return {"error": "請先調用 input_scores() 輸入五維評分"}
        total = sum(self.scores.values())
        avg = total / 5.0
        # 找出強弱項
        strongest = max(self.scores, key=self.scores.get)
        weakest = min(self.scores, key=self.scores.get)

        level = ""
        if avg >= 8.5:
            level = "典範儒商（New Confucian Entrepreneur）"
        elif avg >= 7.0:
            level = "合格的儒商實踐者"
        elif avg >= 5.0:
            level = "儒商修煉中，尚有明顯提升空間"
        else:
            level = "初學者，需從基礎修身做起"

        advice_map = {
            "仁": "建議多關注員工幸福與客戶體驗，踐行'為人之親'，建設擬家庭化組織。",
            "義": "建議強化義利觀，反思經營決策是否符合'見利思義'原則，避免唯利是圖。",
            "禮": "建議完善企業制度與行為規範，將價值觀固化於制，內化於心、外化於行。",
            "智": "建議加強學習型組織建設，提升戰略遠見與知治一致的能力。",
            "信": "建議強化誠信體系，做到人品、企品、產品三品合一，內誠於心、外信於人。"
        }

        return {
            "scores": self.scores.copy(),
            "total": total,
            "average": round(avg, 2),
            "level": level,
            "strongest": (strongest, self.DIMENSIONS[strongest]),
            "weakest": (weakest, self.DIMENSIONS[weakest]),
            "primary_advice": advice_map[weakest],
            "radar_data": [
                {"dimension": k, "score": v, "description": self.DIMENSIONS[k]}
                for k, v in self.scores.items()
            ]
        }


