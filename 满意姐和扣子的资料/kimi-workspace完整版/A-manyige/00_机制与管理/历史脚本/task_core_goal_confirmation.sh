#!/bin/bash
# 满意妞任务核心目标确认脚本
# 2026-03-30 强制固化
# 用途: 接到任何任务后，必须先回答两个问题，经用户确认后才能执行

TASK_NAME="$1"
if [ -z "$TASK_NAME" ]; then
    echo "❌ 错误: 必须提供任务名称"
    echo "用法: $0 <任务名称>"
    exit 1
fi

echo "=================================="
echo "任务核心目标确认机制"
echo "任务: $TASK_NAME"
echo "时间: $(date)"
echo "=================================="
echo ""

echo "【强制要求】接到任务后，必须先回答这两个问题:"
echo ""
echo "问题1: 我为什么要做这个事情?"
echo "  - 表面原因:"
echo "  - 深层原因:"
echo "  - 如果不做，会有什么后果:"
echo ""
echo "问题2: 本来做这个事情是要解决什么问题?"
echo "  - 要解决的表面问题:"
echo "  - 要解决的根因问题:"
echo "  - 解决后应该达到什么状态:"
echo ""

echo "【执行流程】"
echo "1. 接到任务 → 立即自问这两个问题"
echo "2. 写下我的理解 → 提交给用户确认"
echo "3. 用户确认后 → 将这两个答案作为【项目核心目标】固化到任务中"
echo "4. 执行过程中 → 每一步检查: 是否偏离初衷? 是否自动执行?"
echo "5. 完成后 → 验证: 是否解决了原本要解决的问题?"
echo ""

echo "【禁止事项】"
echo "❌ 未经确认就执行"
echo "❌ 不理解为什么要做就盲目做"
echo "❌ 执行过程中忘记初衷"
echo "❌ 用'完成任务'代替'解决问题'"
echo ""

echo "【物理化要求】"
echo "✅ 每个任务创建时，必须在任务文档开头写入这两个问题的答案"
echo "✅ 任务进行中，每小时回顾一次这两个问题"
echo "✅ 任务完成后，验证是否达成这两个问题描述的目标"
echo ""

echo "=================================="
echo "请回答上述两个问题，提交用户确认"
echo "=================================="
